def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--test-audit", type=Path, required=True)
    parser.add_argument("--eval-audit", type=Path, required=True)
    parser.add_argument("--test-archive-sha256", required=True)
    parser.add_argument("--eval-archive-sha256", required=True)
    parser.add_argument("--population-v2", type=Path, required=True)
    parser.add_argument("--selection-output", type=Path, required=True)
    parser.add_argument("--segment-root", type=Path)
    parser.add_argument("--population-output", type=Path)
    parser.add_argument("--inference-output", type=Path)
    parser.add_argument("--evaluation-output", type=Path)
    args = parser.parse_args()
    rows = eligible_rows(args.test_audit, "TEST") + eligible_rows(args.eval_audit, "EVAL")
    primary, reserve, speakers, ranking = select_rows(rows)
    selection = selection_record(rows, primary, reserve, speakers, ranking, args.test_archive_sha256, args.eval_archive_sha256)
    args.selection_output.write_text(json.dumps(selection, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    if args.population_output:
        if not args.segment_root or not args.inference_output or not args.evaluation_output:
            raise ValueError("segment, inference, and evaluation outputs are required with population output")
        population, inference, evaluation = build_population(args, selection, primary, reserve, speakers)
        args.population_output.write_text(json.dumps(population, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
        args.inference_output.write_text(json.dumps(inference, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
        args.evaluation_output.write_text(json.dumps(evaluation, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
