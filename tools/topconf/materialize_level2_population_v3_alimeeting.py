"""Materialize the single Phase4.9 V3 population using AliMeeting.

Selection is fixed from TextGrid interval metadata before any segment is
written.  Segment extraction preserves the parent recording hash and exact
time offsets.  No model, prediction, label, quality score, or outcome is
read or generated by this tool.
"""

